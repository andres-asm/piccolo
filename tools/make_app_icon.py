#!/usr/bin/env python3
"""Embed piccolo's window icon PNGs (assets/branding/png) into src/app_icon.h.

The PNGs come from the SVGs in assets/branding (rendered with Inkscape, see
assets/branding/README.md). The header holds the PNG bytes as they are; SDL
decodes them at start (SDL_LoadPNG_IO) and hands every size to the window
manager as one icon with alternate images.

No dependencies beyond the Python standard library.

    python3 tools/make_app_icon.py
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PNG_DIR = os.path.join(ROOT, "assets", "branding", "png")
OUT = os.path.join(ROOT, "src", "app_icon.h")

# The first one is the base image, the rest are alternates.
SIZES = [256, 128, 64, 48, 32, 24, 16]


def main():
    lines = []
    lines.append("#pragma once")
    lines.append("")
    lines.append("// Generated by tools/make_app_icon.py from assets/branding/png. Don't edit.")
    lines.append("// piccolo's window icon: PNG files, largest first.")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append('#include "app_shell.h"')
    lines.append("")
    for size in SIZES:
        path = os.path.join(PNG_DIR, "piccolo-icon-%d.png" % size)
        with open(path, "rb") as f:
            data = f.read()
        lines.append("static const uint8_t app_icon_png_%d[%d] = {" % (size, len(data)))
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
        lines.append("};")
        lines.append("")
    lines.append("static const AppShellIcon app_icon_images[] = {")
    for size in SIZES:
        lines.append("    {app_icon_png_%d, sizeof(app_icon_png_%d)}," % (size, size))
    lines.append("};")
    lines.append("")
    lines.append("static const int32_t app_icon_image_count = %d;" % len(SIZES))
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
