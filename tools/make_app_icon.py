#!/usr/bin/env python3
"""Embed piccolo's icon PNGs (assets/branding/png) into the program.

Writes two files from the same PNGs:

- src/app_icon.h: the window icon. The header holds the PNG bytes as they
  are; SDL decodes them at start (SDL_LoadPNG_IO) and hands every size to the
  window manager as one icon with alternate images.
- assets/windows/piccolo.ico: the .exe's icon on Windows (Explorer, the
  taskbar, shortcuts), compiled into piccolo.exe as a resource
  (src/piccolo.rc.in). Its images are the same PNGs, stored as they are (ICO
  files may hold PNGs since Windows Vista).

The PNGs come from the SVGs in assets/branding (rendered with Inkscape, see
assets/branding/README.md).

No dependencies beyond the Python standard library.

    python3 tools/make_app_icon.py
"""

import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PNG_DIR = os.path.join(ROOT, "assets", "branding", "png")
OUT = os.path.join(ROOT, "src", "app_icon.h")
ICO_OUT = os.path.join(ROOT, "assets", "windows", "piccolo.ico")

# The first one is the base image, the rest are alternates. 256 is also the
# largest an ICO entry can say.
SIZES = [256, 128, 64, 48, 32, 24, 16]


def read_png(size):
    with open(os.path.join(PNG_DIR, "piccolo-icon-%d.png" % size), "rb") as f:
        return f.read()


def write_ico():
    # ICONDIR, then one ICONDIRENTRY per image, then the images. Smallest
    # first, as Windows' own icons are.
    images = [(size, read_png(size)) for size in sorted(SIZES)]
    header = struct.pack("<HHH", 0, 1, len(images))   # reserved, type 1 = icon, count
    offset = len(header) + 16 * len(images)
    entries = b""
    for size, data in images:
        side = 0 if size >= 256 else size   # 0 means 256
        # width, height, palette colors, reserved, planes, bits per pixel, bytes, offset
        entries += struct.pack("<BBBBHHII", side, side, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    os.makedirs(os.path.dirname(ICO_OUT), exist_ok=True)
    with open(ICO_OUT, "wb") as f:
        f.write(header + entries + b"".join(data for _, data in images))
    print("wrote %s" % ICO_OUT)


def main():
    write_ico()
    lines = []
    lines.append("#pragma once")
    lines.append("")
    lines.append("// Generated by tools/make_app_icon.py from assets/branding/png. Don't edit.")
    lines.append("// (The .exe's icon on Windows comes from the same PNGs: assets/windows/piccolo.ico.)")
    lines.append("// piccolo's window icon: PNG files, largest first.")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append('#include "app_shell.h"')
    lines.append("")
    for size in SIZES:
        data = read_png(size)
        lines.append("static const uint8_t app_icon_png_%d[%d] = {" % (size, len(data)))
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
        lines.append("};")
        lines.append("")
    lines.append("static const AppShellIcon app_icon_images[] = {")
    for size in SIZES:
        lines.append("    {app_icon_png_%d, sizeof(app_icon_png_%d)}," % (size, size))
    lines.append("};")
    lines.append("")
    lines.append("static const int32_t app_icon_image_count = %d;" % len(SIZES))
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
